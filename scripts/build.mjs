// npm run build [-- <dir>]: writes the library QACI Duo reads (catalog.json, packages, generated team files).
// The publish workflow runs it after each merge to main and pushes the result to the `library` branch.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildCatalog, libraryFiles, validatePackage } from "./lib.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, process.argv[2] ?? "dist");
if (out === root || !out.startsWith(`${root}/`)) throw new Error("The output folder must be inside the repository");

const entries = [];
const written = [];
rmSync(out, { recursive: true, force: true });
for (const name of readdirSync(join(root, "packages")).filter((name) => name.endsWith(".md")).sort()) {
  const slug = name.slice(0, -".md".length);
  const markdown = readFileSync(join(root, "packages", name), "utf8");
  const problems = validatePackage(markdown, slug);
  if (problems.length) throw new Error(`packages/${name} is invalid; run npm test`);
  const { entry, files } = libraryFiles(slug, markdown);
  entries.push(entry);
  for (const file of files) {
    mkdirSync(dirname(join(out, file.path)), { recursive: true });
    writeFileSync(join(out, file.path), file.content);
    written.push(file.path);
  }
}
writeFileSync(join(out, "catalog.json"), `${JSON.stringify(buildCatalog(entries), null, 2)}\n`);
writeFileSync(
  join(out, "README.md"),
  "# QACI Duo team library (published)\n\nThis branch is generated by the publish workflow from `main`. Do not edit it; open a pull request against `main`.\n",
);
console.log(`Built ${entries.length} teams, ${written.length + 2} files in ${out}`);
